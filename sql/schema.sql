-- Compatible with databases created by v0.1-v0.3.1.
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS members (id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL UNIQUE COLLATE NOCASE,created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS tasks (
 id INTEGER PRIMARY KEY AUTOINCREMENT,title TEXT NOT NULL,start_date TEXT NOT NULL,
 recurrence TEXT NOT NULL CHECK (recurrence IN ('once','daily','weekly','interval','monthly')),
 weekdays INTEGER NOT NULL DEFAULT 0,member_id INTEGER REFERENCES members(id) ON DELETE SET NULL,
 archived_at TEXT,created_at TEXT NOT NULL, schedule_kind TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS completions (
 task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,day TEXT NOT NULL,
 done INTEGER NOT NULL DEFAULT 0 CHECK (done IN (0,1)),completed_at TEXT,
 PRIMARY KEY(task_id,day)
);
CREATE TABLE IF NOT EXISTS shopping (id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL,quantity TEXT NOT NULL DEFAULT '',bought INTEGER NOT NULL DEFAULT 0 CHECK(bought IN (0,1)),created_at TEXT NOT NULL,bought_at TEXT);
CREATE TABLE IF NOT EXISTS task_moves (id INTEGER PRIMARY KEY AUTOINCREMENT,task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,from_date TEXT NOT NULL,to_date TEXT NOT NULL,moved_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS categories (
 id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL UNIQUE COLLATE NOCASE,
 symbol TEXT NOT NULL DEFAULT '•',position INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS quick_tasks (
 id INTEGER PRIMARY KEY AUTOINCREMENT,category_id INTEGER NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
 title TEXT NOT NULL,member_id INTEGER REFERENCES members(id) ON DELETE SET NULL,
 favorite INTEGER NOT NULL DEFAULT 0,uses INTEGER NOT NULL DEFAULT 0,
 last_used TEXT,position INTEGER NOT NULL DEFAULT 0,
 UNIQUE(category_id,title)
);
CREATE TABLE IF NOT EXISTS shopping_catalog (
 id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL UNIQUE COLLATE NOCASE,
 category TEXT NOT NULL DEFAULT 'Inne',quantity TEXT NOT NULL DEFAULT '',favorite INTEGER NOT NULL DEFAULT 0,
 uses INTEGER NOT NULL DEFAULT 0,last_used TEXT
);
CREATE TABLE IF NOT EXISTS day_templates (id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL UNIQUE COLLATE NOCASE,created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS day_template_items (id INTEGER PRIMARY KEY AUTOINCREMENT,template_id INTEGER NOT NULL REFERENCES day_templates(id) ON DELETE CASCADE,title TEXT NOT NULL,member_id INTEGER REFERENCES members(id) ON DELETE SET NULL,position INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS shopping_sets (id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL UNIQUE COLLATE NOCASE,created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS shopping_set_items (id INTEGER PRIMARY KEY AUTOINCREMENT,set_id INTEGER NOT NULL REFERENCES shopping_sets(id) ON DELETE CASCADE,name TEXT NOT NULL,quantity TEXT NOT NULL DEFAULT '',category TEXT NOT NULL DEFAULT 'Inne');
CREATE TABLE IF NOT EXISTS task_skips (task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,day TEXT NOT NULL,skipped_at TEXT NOT NULL,PRIMARY KEY(task_id,day));
CREATE TABLE IF NOT EXISTS plan_snapshots (
 task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,day TEXT NOT NULL,
 title TEXT NOT NULL,member_name TEXT NOT NULL DEFAULT '',member_id INTEGER,captured_at TEXT NOT NULL,
 PRIMARY KEY(task_id,day)
);
CREATE TABLE IF NOT EXISTS shopping_history (id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL,quantity TEXT NOT NULL,category TEXT NOT NULL DEFAULT 'Inne',bought_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS subtasks (id INTEGER PRIMARY KEY AUTOINCREMENT,task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,title TEXT NOT NULL,position INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS subtask_checks (subtask_id INTEGER NOT NULL REFERENCES subtasks(id) ON DELETE CASCADE,day TEXT NOT NULL,done INTEGER NOT NULL DEFAULT 1,PRIMARY KEY(subtask_id,day));
CREATE TABLE IF NOT EXISTS notes (id INTEGER PRIMARY KEY AUTOINCREMENT,text TEXT NOT NULL,created_at TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS idx_tasks_start ON tasks(start_date);
CREATE INDEX IF NOT EXISTS idx_completion_day ON completions(day);
CREATE INDEX IF NOT EXISTS idx_shopping_bought ON shopping(bought);
CREATE INDEX IF NOT EXISTS idx_moves_task ON task_moves(task_id);
CREATE INDEX IF NOT EXISTS idx_plan_snapshots_day ON plan_snapshots(day);
CREATE INDEX IF NOT EXISTS idx_history_bought ON shopping_history(bought_at);
